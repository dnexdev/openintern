// Command gen writes internal/unicodex/pictographic_table.go from
// internal/unicodex/emoji-data.txt (Unicode License v3).
//
//	go generate ./internal/unicodex
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

func main() {
	// Works from the repo root (go run) and from the package (go generate).
	dir := "internal/unicodex/"
	if _, err := os.Stat("emoji-data.txt"); err == nil {
		dir = ""
	}
	f, err := os.Open(dir + "emoji-data.txt")
	if err != nil {
		fail(err)
	}
	defer f.Close()

	type rng struct{ lo, hi uint32 }
	var ranges []rng
	version := ""
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if v, ok := strings.CutPrefix(line, "# Version: "); ok {
			version = strings.TrimSpace(v)
		}
		if i := strings.IndexByte(line, '#'); i >= 0 {
			line = line[:i]
		}
		fields := strings.Split(line, ";")
		if len(fields) != 2 || strings.TrimSpace(fields[1]) != "Extended_Pictographic" {
			continue
		}
		cp := strings.TrimSpace(fields[0])
		lo, hi, found := strings.Cut(cp, "..")
		if !found {
			hi = lo
		}
		a, err1 := strconv.ParseUint(lo, 16, 32)
		b, err2 := strconv.ParseUint(hi, 16, 32)
		if err1 != nil || err2 != nil {
			fail(fmt.Errorf("bad code point range %q", cp))
		}
		ranges = append(ranges, rng{uint32(a), uint32(b)})
	}
	if err := sc.Err(); err != nil {
		fail(err)
	}
	sort.Slice(ranges, func(i, j int) bool { return ranges[i].lo < ranges[j].lo })
	// Merge adjacent ranges.
	merged := ranges[:0]
	for _, r := range ranges {
		if n := len(merged); n > 0 && r.lo <= merged[n-1].hi+1 {
			if r.hi > merged[n-1].hi {
				merged[n-1].hi = r.hi
			}
			continue
		}
		merged = append(merged, r)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/unicodex/internal/gen from emoji-data.txt (Unicode %s). DO NOT EDIT.\n\n", version)
	b.WriteString("package unicodex\n\n")
	fmt.Fprintf(&b, "// EmojiVersion is the Unicode emoji data version of pictographicRanges.\nconst EmojiVersion = %q\n\n", version)
	b.WriteString("// pictographicRanges are the inclusive Extended_Pictographic ranges, sorted and merged.\n")
	b.WriteString("var pictographicRanges = [][2]rune{\n")
	for _, r := range merged {
		fmt.Fprintf(&b, "\t{0x%04X, 0x%04X},\n", r.lo, r.hi)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(dir+"pictographic_table.go", src, 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "gen:", err)
	os.Exit(1)
}
