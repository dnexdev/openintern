/**
 * Build packages/db/src/apply-hosts.generated.ts from data/apply-hosts.tsv plus
 * the hosts each company's board token implies (e.g. greenhouse token `acme`
 * → job-boards.greenhouse.io/acme/). The site has no filesystem at runtime,
 * so the table is compiled in.
 *
 *   pnpm gen-apply-hosts          write the module
 *   pnpm gen-apply-hosts --check  fail if it is out of date (CI)
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadCompanyYamlFiles } from "./sync-companies.js";
import { parseWorkdayToken } from "./workday.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "../../..");
const tsvPath = path.join(root, "data/apply-hosts.tsv");
const outPath = path.join(root, "packages/db/src/apply-hosts.generated.ts");

type Entry = [host: string, prefix: string];

/** Hosts a board token implies; empty when the ATS gives no safe pattern. */
export function derivedHosts(ats: string, token: string): Entry[] {
  const t = token.trim();
  const seg = (s: string) => `/${s.toLowerCase()}/`;
  switch (ats) {
    case "greenhouse":
      return [
        ["job-boards.greenhouse.io", seg(t)],
        ["boards.greenhouse.io", seg(t)],
        ["job-boards.eu.greenhouse.io", seg(t)],
      ];
    case "lever":
      return [
        ["jobs.lever.co", seg(t)],
        ["jobs.eu.lever.co", seg(t)],
      ];
    case "ashby":
      return [["jobs.ashbyhq.com", seg(t)]];
    case "smartrecruiters":
      return [["jobs.smartrecruiters.com", seg(t)]];
    case "rippling":
      return [["ats.rippling.com", seg(t)]];
    case "workable":
      return [["apply.workable.com", seg(t)]];
    case "recruitee":
      return /^[a-z0-9-]+$/i.test(t) ? [[`${t.toLowerCase()}.recruitee.com`, "/"]] : [];
    case "bamboohr":
      return /^[a-z0-9-]+$/i.test(t) ? [[`${t.toLowerCase()}.bamboohr.com`, "/"]] : [];
    case "workday": {
      const b = parseWorkdayToken(t);
      return b ? [[`${b.tenant.toLowerCase()}.${b.datacenter}.myworkdayjobs.com`, "/"]] : [];
    }
    case "tiktok":
      return [["lifeattiktok.com", "/search/"]];
    case "bytedance":
      return [["joinbytedance.com", "/search/"]];
    case "tesla":
      return [["www.tesla.com", "/careers/"]];
    case "citadel":
      return [["www.citadel.com", "/careers/"]];
    case "citadel_securities":
      return [["www.citadelsecurities.com", "/careers/"]];
    default:
      return [];
  }
}

export function parseApplyHostsTsv(text: string): { company: string; host: string; prefix: string }[] {
  const rows: { company: string; host: string; prefix: string }[] = [];
  const errors: string[] = [];
  text.split("\n").forEach((line, i) => {
    if (!line.trim() || line.startsWith("#") || line.startsWith("company\t")) return;
    const [company, host, prefix] = line.split("\t");
    if (!company || !host || !prefix) return errors.push(`line ${i + 1}: needs company, host, path_prefix`);
    if (host !== host.toLowerCase() || !/^[a-z0-9.-]+$/.test(host)) errors.push(`line ${i + 1}: bad host ${host}`);
    if (!prefix.startsWith("/") || !prefix.endsWith("/")) errors.push(`line ${i + 1}: prefix must start and end with /`);
    rows.push({ company, host, prefix });
  });
  if (errors.length) throw new Error(`data/apply-hosts.tsv: ${errors.join("; ")}`);
  return rows;
}

export async function buildApplyHostsModule(): Promise<string> {
  const table = new Map<string, Set<string>>();
  const add = (company: string, host: string, prefix: string) => {
    const set = table.get(company) ?? new Set<string>();
    set.add(`${host}\t${prefix}`);
    table.set(company, set);
  };
  const companies = await loadCompanyYamlFiles();
  const slugs = new Set(companies.map((c) => c.slug));
  for (const c of companies) for (const [h, p] of derivedHosts(c.ats, c.board_token)) add(c.slug, h, p);
  for (const r of parseApplyHostsTsv(await fs.readFile(tsvPath, "utf8"))) {
    if (!slugs.has(r.company)) continue; // company left the registry
    add(r.company, r.host, r.prefix);
  }
  const lines = [...table.keys()].sort().map((slug) => {
    const entries = [...table.get(slug)!].sort().map((e) => {
      const [h, p] = e.split("\t");
      return `[${JSON.stringify(h)}, ${JSON.stringify(p)}]`;
    });
    return `  ${JSON.stringify(slug)}: [${entries.join(", ")}],`;
  });
  return [
    "// Generated by `pnpm gen-apply-hosts` from data/apply-hosts.tsv and data/companies. Do not edit.",
    'import type { ApplyHostTable } from "./apply-hosts";',
    "",
    "export const APPLY_HOSTS: ApplyHostTable = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const next = await buildApplyHostsModule();
  const current = await fs.readFile(outPath, "utf8").catch(() => "");
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("apply-hosts.generated.ts is out of date; run pnpm gen-apply-hosts");
      process.exit(1);
    }
    console.log("apply-hosts: generated table is up to date");
  } else {
    await fs.writeFile(outPath, next);
    console.log(`apply-hosts: wrote ${outPath}`);
  }
}
