/**
 * Build packages/db/src/aliases.generated.ts from data/company-aliases.tsv and
 * data/job-aliases.tsv, so the site can redirect old links without a
 * filesystem at runtime.
 *
 *   pnpm gen-aliases          write the module
 *   pnpm gen-aliases --check  fail if it is out of date (CI)
 */
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadCompanyYamlFiles } from "./sync-companies.js";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "../../..");
const outPath = path.join(root, "packages/db/src/aliases.generated.ts");
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

function rows(text: string, header: string): string[][] {
  return text
    .split("\n")
    .filter((l) => l.trim() && !l.startsWith("#") && !l.startsWith(header))
    .map((l) => l.split("\t"));
}

export async function buildAliasesModule(): Promise<string> {
  const slugs = new Set((await loadCompanyYamlFiles()).map((c) => c.slug));
  const errors: string[] = [];
  const companies = new Map<string, string>();
  for (const [oldSlug, newSlug] of rows(await fs.readFile(path.join(root, "data/company-aliases.tsv"), "utf8"), "old_slug\t")) {
    if (!oldSlug || !newSlug) continue;
    if (slugs.has(oldSlug)) errors.push(`company alias ${oldSlug} is still a registry slug`);
    if (!slugs.has(newSlug)) errors.push(`company alias target ${newSlug} is not in the registry`);
    companies.set(oldSlug, newSlug);
  }
  const jobsMap = new Map<string, string>();
  for (const [oldId, newId] of rows(await fs.readFile(path.join(root, "data/job-aliases.tsv"), "utf8"), "old_job_id\t")) {
    if (!UUID.test(oldId ?? "") || !UUID.test(newId ?? "")) errors.push(`bad job alias ${oldId} → ${newId}`);
    else jobsMap.set(oldId!, newId!);
  }
  if (errors.length) throw new Error(errors.join("; "));
  const entries = (m: Map<string, string>) =>
    [...m].sort().map(([a, b]) => `  [${JSON.stringify(a)}, ${JSON.stringify(b)}],`);
  return [
    "// Generated by `pnpm gen-aliases` from data/company-aliases.tsv and data/job-aliases.tsv. Do not edit.",
    "",
    "export const COMPANY_ALIASES: ReadonlyMap<string, string> = new Map([",
    ...entries(companies),
    "]);",
    "",
    "export const JOB_ALIASES: ReadonlyMap<string, string> = new Map([",
    ...entries(jobsMap),
    "]);",
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const next = await buildAliasesModule();
  const current = await fs.readFile(outPath, "utf8").catch(() => "");
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("aliases.generated.ts is out of date; run pnpm gen-aliases");
      process.exit(1);
    }
    console.log("aliases: generated table is up to date");
  } else {
    await fs.writeFile(outPath, next);
    console.log(`aliases: wrote ${outPath}`);
  }
}
